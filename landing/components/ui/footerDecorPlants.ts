/**
 * Оба размера заданы явно, `auto` тут нельзя: у выгрузки целочисленный бокс (146×170
 * против настоящих 145.128×169.626), и высота «по файлу» увела бы пропорцию на пол
 * процента от макетной. Числа `w`/`h` считаны от одной и той же стороны, поэтому масштаб
 * остаётся равномерным и при подмене `--footer-u` на телефоне.
 */
export function footerDecorStyle(p: FooterDecorPlant): CSSProperties {
  const u = (n: number) => `calc(${n} * var(--footer-u))`
  // Размер меряется своей единицей: у помеченных её подменяет `.footer-plant-big`
  // (globals.css), у остальных фолбэк возвращает ту же `--footer-u`, что и у смещений.
  // Одна переменная вместо прежней пары «единица + множитель»: разрастание на телефоне —
  // это ДРУГАЯ опорная сторона, а не то же число, помноженное на константу.
  const size = (n: number) => `calc(${n} * var(--footer-su, var(--footer-u)))`

  const style: CSSProperties = { width: size(p.w), height: size(p.h) }
  if (p.anchorX === 'left') style.left = u(p.x)
  else style.right = u(p.x)
  if (p.anchorY === 'top') style.top = `${p.y}%`
  else style.bottom = `${p.y}%`
  // Сам трансформ собирает `.footer-plant-tf`: тут только величины, чтобы числа жили в
  // таблице рядом с остальной геометрией, а брейкпоинт — в CSS.
  if (p.liftPhone) (style as Record<string, string>)['--footer-lift'] = `${p.liftPhone}px`
  if (p.rotate) (style as Record<string, string>)['--footer-rot'] = `${p.rotate}deg`

  return style
}
