/**
 * Растения на карточке футера — фрейм «Leaves» из Figma (2604:17925 внутри
 * `device=Desktop` 2516:16560).
 *
 * ── Готовые срезы, а не файлы с полки ──
 *
 * Каждый куст в макете — это ГРУППА из 6–13 отдельных вектор-слоёв, у каждого свой
 * поворот, скос и неравномерный масштаб (`rotate(-59.21deg) scale-y-97 skew-x(1.68deg)`).
 * Собирать это из общей полки `header/decor` нечем: таких файлов там нет, а разложить
 * группу на слои значит внести в разметку 40 картинок с рукописными матрицами. Поэтому
 * взят приём тарифов 1 и 4 — каждая группа выгружена из Figma ОДНИМ svg
 * (`public/SVG/footer/decor`), и ставится по своему же окну.
 *
 * ── Откуда числа ──
 *
 * Макетная карточка — 939×1108 (сам символ 2516:16560, у него и радиус, и падинги).
 * Фрейм Leaves лежит в ней со смещением (−89, 92) и сам по себе 1657.8×1748.2, то есть
 * сильно вылезает за карточку. Поэтому координаты каждой группы считались так:
 *
 *   card_x = leaves_left − 89        card_y = leaves_top + 92
 *
 * где `leaves_left/top` — AABB группы из design context (метаданные Figma тут НЕ годятся:
 * они отдают трансляцию трансформа, а не AABB — у синего листа расхождение ровно
 * 209.61·sin30° = 104.8px).
 *
 * ── Подложку кадра из выгрузки надо снимать ──
 *
 * Тем же клипом Figma кладёт в файл и ОКРУЖЕНИЕ среза: `rect` холста `#1E1E1E`, пунктирную
 * рамку секции `#8A38F5` и заливку самой карточки `#FFFCE5` во весь viewBox. Последняя и
 * читается на странице как белая плашка под растением: слой стоит на `opacity: 0.8` поверх
 * полупрозрачного стекла, так что непрозрачный прямоугольник под кустом виден целиком.
 * После любой перевыгрузки эти три элемента удалять; гард `npm run verify:footer-decor`
 * проверяет исходники до того, как поднимет браузер.
 *
 * Проверка сошлась на самом экспорте: Figma режет выгрузку по клипу карточки, и размеры
 * файлов совпали с пересечением посчитанных боксов с прямоугольником 939×1108
 * ДО ПИКСЕЛЯ — пальма 1238.7×1260.2 → 860×828, цветок 271.6×260.4 → 176×160. Две
 * независимые сходимости на двух объектах — этого достаточно, отдельный фиттер не нужен.
 *
 * Пятая группа макета (2580:47851, ещё один синий лист) в таблицу не попала: её бокс
 * начинается на y=1178 при высоте карточки 1108, то есть она целиком за нижним краем и
 * в макете не видна.
 *
 * ── Единица ──
 *
 * `--footer-u` (globals.css) — процент КОРОТКОЙ стороны карточки: `1cqh` от lg, `1cqw`
 * ниже. Ширина карточки в проде — до 1696 против макетных 939, а высота почти макетная,
 * так что в долях ширины куст раздуло бы вдвое там, где карточка по высоте не растёт.
 * В долях высоты кроп макетный, а широкая карточка просто показывает больше плоского
 * цвета в середине — ровно там, где лежит текст. На телефоне карточка становится узкой
 * и очень высокой, короткая сторона у неё уже ширина, — единица переезжает на неё, иначе
 * пальма выросла бы до высоты списка FAQ.
 *
 * Вертикальная привязка при этом всегда в ПРОЦЕНТАХ ВЫСОТЫ, а не в `--footer-u`: у двух
 * угловых кустов это ноль (они прижаты к низу), а два летящих листа держатся своей доли
 * карточки на любой ширине.
 */
export type FooterDecorPlant = {
  /** файл в `public/SVG/footer/decor` */
  file: string
  /** грань, от которой отмеряется ближайший край картинки */
  anchorX: 'left' | 'right'
  /** смещение от этой грани, в единицах `--footer-u` */
  x: number
  anchorY: 'top' | 'bottom'
  /** смещение от этой грани, в процентах ВЫСОТЫ карточки */
  y: number
  /** размеры собственного бокса среза, в единицах `--footer-u` */
  w: number
  h: number
  /**
   * Растение крупнее макетной доли на телефоне — множитель `PHONE_BLOOM`, класс
   * `.footer-plant-big` в globals.css. Стоит у трёх мелких (розовый и синий лист, жёлтый
   * цветок); пальма и на телефоне занимает три четверти карточки, её раздувать некуда.
   */
  big?: true
  /**
   * Подъём на телефоне, в ПИКСЕЛЯХ (класс `.footer-plant-tf` в globals.css). Не в
   * процентах высоты, как якорь `y`: высота карточки на телефоне зависит от локали, и
   * одна доля дала бы три разных подъёма. На десктопе сдвиг гасится.
   */
  liftPhone?: number
  /**
   * Поворот рисунка, в градусах ПО ЧАСОВОЙ (знак как у CSS `rotate()`). В отличие от
   * подъёма — на всех ширинах: это ориентация арта, а не раскладка. Крутится вокруг центра
   * бокса, поэтому якоря и размеры остаются прежними, а вырасти может только AABB.
   */
  rotate?: number
}

/**
 * Во сколько раз мелкие растения крупнее макетной доли на ТЕЛЕФОНЕ — и одновременно
 * порог, за которым это разрастание выключается: работает оно, пока карточка выше своей
 * ширины хотя бы во столько же раз. Само правило живёт в globals.css
 * (`.footer-plant-big`: `--footer-su: min(4cqw, 1cqh)`) — контейнерные единицы
 * инлайн-стилю доступны, а вот выбрать между ними он не может, — а здесь число нужно
 * гарду: `npm run verify:footer-decor` считает по нему ожидаемый размер и упадёт, если два
 * места разъедутся.
 *
 * Брейкпоинта тут нет намеренно. Прежний множитель, включённый по `< lg`, держал долю
 * постоянной — 63% ширины карточки и на 390, и на 1023, где карточка уже почти квадрат, —
 * и схлопывался втрое на 1024. Сравнение двух сторон делает переход непрерывным и само
 * гаснет на десктопных пропорциях.
 */
export const PHONE_BLOOM = 4

