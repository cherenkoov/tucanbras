/**
 * Ссылка из CMS считается живой, только если в ней стоит настоящий адрес.
 *
 * Пустая строка, пробелы и заглушка '#' означают «канал/страница ещё не
 * запущены»: футер рисует такой пункт приглушённым, некликабельным, с
 * подсказкой «скоро». Раньше это правило было записано дважды — инлайном
 * для юридических ссылок и захардкоженной картой URL для соцсетей, из-за
 * чего адрес соцсети, вписанный в админке, вообще ни на что не влиял.
 */
export function activeHref(href: string | null | undefined): string | null {
  if (typeof href !== 'string') return null

  const trimmed = href.trim()
  if (trimmed === '' || trimmed === '#') return null

  return trimmed
}
